export const CATALOG = new Map(entries.map((entry) => [entry.id, entry]));

export function getCatalogEntry(modelId) {
  return typeof modelId === "string" ? CATALOG.get(modelId) ?? null : null;
}

export function isCatalogSample(modelId, sampleId) {
  const entry = getCatalogEntry(modelId);
  if (!entry || typeof sampleId !== "string") return false;
  const prefix = `${entry.dataset}-${entry.id}-${entry.digest.slice(0, 12)}-`;
  if (!sampleId.startsWith(prefix) || !/^\d{6}$/.test(sampleId.slice(prefix.length))) return false;
  const sourceId = Number(sampleId.slice(prefix.length));
  return entry.sourceIds.includes(sourceId);
}
